import {readFile,writeFile} from 'node:fs/promises';
const read=name=>readFile(new URL(name,import.meta.url),'utf8');
const data=(await read('data.js')).replaceAll('export const ','const ');
const roadmap=(await read('roadmap.js')).replaceAll('export const ','const ');
const ids=(await read('ids.js')).replaceAll('export function ','function ');
const engineSource=await read('engine.js');
const names=[...engineSource.matchAll(/export (?:const|function) (\w+)/g)].map(x=>x[1]);
const engine=engineSource.replace(/^import .*;\n/gm,'').replaceAll('export const ','const ').replaceAll('export function ','function ');
const storageSource=await read('storage.js');
const storageNames=[...storageSource.matchAll(/export (?:const|function) (\w+)/g)].map(x=>x[1]);
const storage=storageSource.replace(/^import .*;\n/gm,'').replaceAll('export const ','const ').replaceAll('export function ','function ');
const app=(await read('app.js')).replace(/^import .*;\n/gm,'');
const js=`${data}\n${roadmap}\n${ids}\nconst E=(()=>{${engine}\nreturn {${names.join(',')}};})();\nconst P=(()=>{const {createState,parseState,serializeState}=E;\n${storage}\nreturn {${storageNames.join(',')}};})();\n${app}`;
let html=(await read('index.html')).replace('<link rel="stylesheet" href="style.css">',`<style>${await read('style.css')}</style>`).replace('<script type="module" src="app.js"></script>',`<script type="module">${js.replaceAll('</script','<\\/script')}</script>`);
await writeFile(new URL('ENTRE-TRILHAS.html',import.meta.url),html);
console.log('ENTRE-TRILHAS.html gerado: sem dependências, fontes ou rede externa.');
